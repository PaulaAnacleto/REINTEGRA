                <h2>1. Introdução</h2>
                <p>A Reintegra ("nós", "nosso" ou "nossa") está comprometida em proteger a privacidade e segurança dos dados pessoais de nossos usuários. Esta Política de Privacidade descreve como coletamos, usamos, armazenamos e protegemos suas informações pessoais quando você utiliza nossos serviços.</p>
                
                <h2>2. Informações que Coletamos</h2>
                <p>Podemos coletar as seguintes categorias de informações pessoais:</p>
                <ul>
                    <li><strong>Informações de Identificação:</strong> nome completo, CPF, RG, data de nascimento, endereço residencial;</li>
                    <li><strong>Informações de Contato:</strong> endereço de e-mail, número de telefone, WhatsApp;</li>
                    <li><strong>Informações de Navegação:</strong> endereço IP, tipo de navegador, páginas visitadas, tempo de acesso;</li>
                    <li><strong>Informações Fornecidas:</strong> dados inseridos em formulários, mensagens enviadas, preferências de comunicação.</li>
                </ul>

                <h2>3. Como Utilizamos suas Informações</h2>
                <p>Utilizamos as informações coletadas para os seguintes propósitos:</p>
                <ul>
                    <li>Fornecer, operar e manter nossos serviços;</li>
                    <li>Processar suas solicitações e responder às suas dúvidas;</li>
                    <li>Enviar comunicações relacionadas aos nossos serviços;</li>
                    <li>Melhorar a experiência do usuário e personalizar nossos serviços;</li>
                    <li>Cumprir obrigações legais e regulatórias;</li>
                    <li>Detectar, prevenir e resolver problemas técnicos ou de segurança.</li>
                </ul>

                <h2>4. Compartilhamento de Informações</h2>
                <p>Não vendemos, alugamos ou compartilhamos suas informações pessoais com terceiros, exceto nas seguintes circunstâncias:</p>
                <ul>
                    <li><strong>Prestadores de Serviços:</strong> podemos compartilhar informações com prestadores de serviços que nos auxiliam na operação de nossos serviços;</li>
                    <li><strong>Obrigações Legais:</strong> quando exigido por lei, ordem judicial ou processo legal;</li>
                    <li><strong>Proteção de Direitos:</strong> para proteger nossos direitos, propriedade ou segurança, bem como de nossos usuários;</li>
                    <li><strong>Consentimento:</strong> quando você nos autoriza expressamente a compartilhar suas informações.</li>
                </ul>

                <h2>5. Segurança dos Dados</h2>
                <p>Implementamos medidas técnicas e organizacionais adequadas para proteger suas informações pessoais contra acesso não autorizado, alteração, divulgação ou destruição. Isso inclui criptografia de dados, controle de acesso restrito e monitoramento contínuo de nossos sistemas.</p>

                <h2>6. Seus Direitos</h2>
                <p>De acordo com a Lei Geral de Proteção de Dados (LGPD), você tem os seguintes direitos:</p>
                <ul>
                    <li>Confirmar a existência de tratamento de seus dados pessoais;</li>
                    <li>Acessar seus dados pessoais;</li>
                    <li>Corrigir dados incompletos, inexatos ou desatualizados;</li>
                    <li>Solicitar a anonimização, bloqueio ou eliminação de dados desnecessários;</li>
                    <li>Solicitar a portabilidade de seus dados;</li>
                    <li>Revogar o consentimento a qualquer momento;</li>
                    <li>Obter informações sobre o compartilhamento de dados.</li>
                </ul>

                <h2>7. Retenção de Dados</h2>
                <p>Retemos suas informações pessoais apenas pelo tempo necessário para cumprir os propósitos descritos nesta política, a menos que um período de retenção mais longo seja exigido ou permitido por lei.</p>

                <h2>8. Cookies e Tecnologias Similares</h2>
                <p>Utilizamos cookies e tecnologias similares para melhorar sua experiência em nosso site. Você pode configurar seu navegador para recusar cookies, mas isso pode afetar a funcionalidade de alguns recursos.</p>

                <h2>9. Alterações nesta Política</h2>
                <p>Podemos atualizar esta Política de Privacidade periodicamente. Notificaremos você sobre quaisquer alterações significativas publicando a nova política em nosso site e atualizando a data de "Última atualização".</p>

